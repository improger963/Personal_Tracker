/**
 * Safe Mobile Haptic Vibration Utility
 * Provides subtle tactile feedback on mobile devices where navigator.vibrate is supported.
 */

export function triggerHaptic(type: 'light' | 'medium' | 'success' | 'warning' = 'light') {
  if (typeof window === 'undefined' || !('vibrate' in navigator)) {
    return;
  }

  try {
    switch (type) {
      case 'light':
        navigator.vibrate(8);
        break;
      case 'medium':
        navigator.vibrate(16);
        break;
      case 'success':
        navigator.vibrate([10, 30, 15]);
        break;
      case 'warning':
        navigator.vibrate([20, 40, 20]);
        break;
    }
  } catch {
    // Graceful fallback if permission or environment restricts vibration
  }
}
